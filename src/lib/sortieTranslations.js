/**
 * Look up a sortie boss or modifier key in the per-locale translation table.
 * Returns the localized string or null if no translation exists.
 */
export function resolveSortieKey(key, locale = 'en') {
  if (!key) return null;
  const modifiers = SORTIE_MODIFIERS[locale];
  const bosses = SORTIE_BOSSES[locale];
  if (modifiers && modifiers[key]) return modifiers[key];
  if (bosses && bosses[key]) return bosses[key];
  // Fallback to English
  if (SORTIE_MODIFIERS.en[key]) return SORTIE_MODIFIERS.en[key];
  if (SORTIE_BOSSES.en[key]) return SORTIE_BOSSES.en[key];
  return null;
}

